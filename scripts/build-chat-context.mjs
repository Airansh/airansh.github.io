import { createHash } from 'node:crypto'
import { readFile, writeFile } from 'node:fs/promises'
import { createElement } from 'react'
import { renderToStaticMarkup } from 'react-dom/server'
import { MemoryRouter } from 'react-router-dom'
import { createServer } from 'vite'
import { projects } from '../src/data/projects.ts'
import { experiences, profile, publications, skills } from '../src/data/profile.ts'
import { diagrams } from '../src/data/diagrams.ts'

const site = 'https://airansh.github.io/'
const docs = []
const add = (id, title, url, content, references = []) =>
  docs.push({
    id,
    title,
    url,
    text: typeof content === 'string' ? content : JSON.stringify(content),
    references,
  })
const server = await createServer({
  configFile: false,
  optimizeDeps: { noDiscovery: true, include: [], entries: [] },
  server: { middlewareMode: true },
  appType: 'custom',
})
try {
  const { default: About } = await server.ssrLoadModule('/src/pages/About.tsx')
  const markup = renderToStaticMarkup(createElement(MemoryRouter, null, createElement(About)))
  const text = markup
    .replace(/<svg\b[\s\S]*?<\/svg>/g, ' ')
    .replace(/<[^>]+>/g, ' ')
    .replace(/&amp;/g, '&')
    .replace(/&#x27;/g, "'")
    .replace(/&quot;/g, '"')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/\s+/g, ' ')
    .trim()
  add('about', 'About, education & leadership', site + '#/about', text)
} finally {
  await server.close()
}
add('skills', 'Engineering toolkit', site + '#/about', skills)
add('contact', 'Contact Vedansh', site + '#/contact', {
  name: profile.name,
  location: profile.location,
  email: profile.email,
  github: profile.github,
  linkedin: profile.linkedin,
})
add(
  'resume',
  'Download resume',
  site + profile.resume + '?v=' + profile.resumeVersion,
  'The current downloadable resume. Experience, education and project details are also available in the portfolio.',
)
add(
  'writing',
  'Practical guides to AI tools',
  profile.writing,
  'Articles by Vedansh on AI tools, agents, custom assistants and practical adoption, published through University of Iowa ITS.',
)
for (const experience of experiences)
  add(
    'experience:' + experience.id,
    experience.role + ' · ' + experience.organization,
    site + '#/experience',
    experience,
  )
for (const publication of publications)
  add(
    'publication:' + publication.id,
    publication.title,
    publication.url || site + '#/research',
    publication,
  )
for (const diagram of diagrams)
  add('architecture:' + diagram.id, diagram.title + ' · architecture', site + '#/architecture', {
    title: diagram.title,
    description: diagram.description,
    kind: diagram.kind,
    code: diagram.code,
  })
for (const project of projects) {
  const {
    id,
    title,
    subtitle,
    summary,
    category,
    context,
    organization,
    period,
    tech,
    contributions,
    outcomes,
    study,
    links,
    github,
    recordings,
  } = project
  const publicStudy = study && {
    problem: study.problem,
    role: study.role,
    requirements: study.requirements,
    implementation: study.implementation,
    validation: study.validation,
    tradeoffs: study.tradeoffs,
    outcome: study.outcome,
    nextSteps: study.nextSteps,
  }
  add(
    'project:' + id,
    title,
    site + '#/work/' + id,
    {
      title,
      subtitle,
      summary,
      category,
      context,
      organization,
      period,
      tech,
      contributions,
      outcomes,
      study: publicStudy,
      links,
      github,
      recordings,
    },
    (recordings || []).map((recording, index) => ({
      id: 'recording:' + id + ':' + index,
      title: recording.title + ' · recorded preview',
      url: recording.url,
    })),
  )
}
const data = {
  profile: { name: profile.name, location: profile.location, email: profile.email },
  catalog: projects.map(({ id, title, organization, tech }) => ({
    id: 'project:' + id,
    title,
    organization,
    tech,
  })),
  docs,
}
const version = createHash('sha256').update(JSON.stringify(data)).digest('hex').slice(0, 12)
const output =
  '// Generated by npm run chat:context from published portfolio content. Do not edit.\nexport default ' +
  JSON.stringify({ version, ...data }, null, 2) +
  '\n'
const path = new URL('../worker/portfolio-context.mjs', import.meta.url)
if (process.argv.includes('--check')) {
  if ((await readFile(path, 'utf8')) !== output)
    throw new Error('Chat context is out of date. Run npm run chat:context.')
  console.log(
    `Chat context matches the portfolio (${projects.length} projects, ${docs.length} sources).`,
  )
} else {
  await writeFile(path, output)
  console.log(
    `Generated public chat context ${version}: ${projects.length} projects, ${docs.length} sources.`,
  )
}
